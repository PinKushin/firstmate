#!/usr/bin/env bash
# fm-boot-identity-lib.sh - the ONE owner of the machine boot identity a task
# record carries, and of the question "has the machine rebooted since?".
#
# Every process dies with a reboot, so a task record that names the boot it was
# launched under can prove its worker is gone once the machine's boot identity
# differs - something no read of a tmux server can establish, because a task
# record carries no tmux socket identity. That is what lets a tmux endpoint that
# reads `missing` be reclaimed after a host or container reboot
# (bin/fm-control-lib.sh's fm_control_endpoint_absence_verdict).
#
# fm_boot_identity prints the current boot identity, or nothing when the
# platform has no reliable one - and then nothing is recorded and every caller
# behaves exactly as it did before this file existed. On Linux the identity is
# /proc/sys/kernel/random/boot_id, regenerated by the kernel on every boot.
# FM_BOOT_ID_FILE overrides the file read, solely so tests can stand in for a
# reboot through the public entry points without one.
#
# fm_boot_identity_changed <recorded> answers the one question callers ask:
# success only when BOTH the recorded and the current identity exist and
# differ. An absent or unreadable identity on either side is "unknown", never
# "changed", so a missing record keeps the conservative refusal.

fm_boot_identity() {
  local file=${FM_BOOT_ID_FILE:-/proc/sys/kernel/random/boot_id} id=
  [ -n "${FM_BOOT_ID_FILE:-}" ] || [ "$(uname -s 2>/dev/null)" = Linux ] || return 0
  [ -r "$file" ] || return 0
  IFS= read -r id <"$file" 2>/dev/null || true
  case "$id" in
    '' | *[!0-9a-fA-F-]*) return 0 ;;
  esac
  printf '%s' "$id"
}

fm_boot_identity_changed() {  # <recorded>
  local recorded=${1-} current
  [ -n "$recorded" ] || return 1
  current=$(fm_boot_identity)
  [ -n "$current" ] && [ "$current" != "$recorded" ]
}
